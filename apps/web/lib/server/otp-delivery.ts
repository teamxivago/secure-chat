import "server-only";
import nodemailer from "nodemailer";
import { env } from "./env";
import { redis } from "./redis";

/** Dev/test hook: remembers the last OTP per destination for 10 minutes (only when explicitly enabled). */
async function devRecord(dest: string, code: string) {
  if (env.devOtpEnabled) await redis().set(`devotp:${dest.toLowerCase()}`, code, "EX", 600);
}

/* ----------------------------- SMS ----------------------------- */

const twilioAuth = () =>
  "Basic " + Buffer.from(`${process.env.TWILIO_ACCOUNT_SID}:${process.env.TWILIO_AUTH_TOKEN}`).toString("base64");

/**
 * Sends the OTP. With Twilio Verify the code is generated by Twilio (our code is ignored and
 * verification is delegated via verifySmsOtp); with Twilio Messaging or MSG91 we send our code.
 */
export async function sendSmsOtp(phone: string, code: string): Promise<void> {
  switch (env.smsProvider) {
    case "twilio-verify": {
      const res = await fetch(`https://verify.twilio.com/v2/Services/${process.env.TWILIO_VERIFY_SERVICE_SID}/Verifications`, {
        method: "POST",
        headers: { Authorization: twilioAuth(), "Content-Type": "application/x-www-form-urlencoded" },
        body: new URLSearchParams({ To: phone, Channel: "sms" }),
      });
      if (!res.ok) throw new Error(`Twilio Verify error ${res.status}`);
      return;
    }
    case "twilio": {
      const res = await fetch(`https://api.twilio.com/2010-04-01/Accounts/${process.env.TWILIO_ACCOUNT_SID}/Messages.json`, {
        method: "POST",
        headers: { Authorization: twilioAuth(), "Content-Type": "application/x-www-form-urlencoded" },
        body: new URLSearchParams({
          To: phone,
          From: process.env.TWILIO_FROM ?? "",
          Body: `Your Veil code: ${code}\n\nDon't share this code with anyone.`,
        }),
      });
      if (!res.ok) throw new Error(`Twilio error ${res.status}`);
      return;
    }
    case "msg91": {
      const res = await fetch("https://control.msg91.com/api/v5/otp?" + new URLSearchParams({
        template_id: process.env.MSG91_TEMPLATE_ID ?? "",
        mobile: phone.replace(/^\+/, ""),
        otp: code,
      }), { method: "POST", headers: { authkey: process.env.MSG91_AUTH_KEY ?? "", "Content-Type": "application/json" } });
      if (!res.ok) throw new Error(`MSG91 error ${res.status}`);
      return;
    }
    case "console": {
      if (process.env.NODE_ENV === "production") throw new Error("console SMS provider is not allowed in production");
      console.info(`[dev sms] OTP for ${phone}: ${code}`);
      await devRecord(phone, code);
      return;
    }
    default:
      throw new Error(`unknown SMS_PROVIDER ${env.smsProvider}`);
  }
}

/** Only used for Twilio Verify, where Twilio owns the code. */
export async function verifySmsOtp(phone: string, code: string): Promise<boolean> {
  const res = await fetch(`https://verify.twilio.com/v2/Services/${process.env.TWILIO_VERIFY_SERVICE_SID}/VerificationCheck`, {
    method: "POST",
    headers: { Authorization: twilioAuth(), "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ To: phone, Code: code }),
  });
  if (!res.ok) return false;
  const data = (await res.json()) as { status?: string };
  return data.status === "approved";
}

/* ----------------------------- Email ----------------------------- */

let transport: nodemailer.Transporter | null = null;

export async function sendEmailOtp(email: string, code: string, type: string): Promise<void> {
  if (env.emailProvider === "console") {
    if (process.env.NODE_ENV === "production") throw new Error("console email provider is not allowed in production");
    console.info(`[dev email] ${type} OTP for ${email}: ${code}`);
    await devRecord(email, code);
    return;
  }
  transport ??= nodemailer.createTransport({
    host: process.env.SMTP_HOST,
    port: Number(process.env.SMTP_PORT ?? 587),
    secure: process.env.SMTP_SECURE === "true",
    auth: process.env.SMTP_USER ? { user: process.env.SMTP_USER, pass: process.env.SMTP_PASSWORD } : undefined,
  });
  await transport.sendMail({
    from: process.env.EMAIL_FROM ?? "Veil <no-reply@veil.app>",
    to: email,
    subject: `${code} is your Veil code`,
    text: `Your Veil verification code is ${code}. It expires in 5 minutes.\n\nIf you didn't request this, ignore this email.`,
    html: `<div style="font-family:Inter,system-ui,sans-serif;max-width:420px;margin:auto;padding:32px">
      <h2 style="margin:0 0 16px;color:#0F0F1A">Your Veil code</h2>
      <p style="font-size:32px;letter-spacing:8px;font-weight:700;color:#00A88E;margin:0 0 16px">${code}</p>
      <p style="color:#555">This code expires in 5 minutes. If you didn't request it, you can ignore this email.</p></div>`,
  });
}
