const seg = typeof Intl !== "undefined" && "Segmenter" in Intl ? new Intl.Segmenter("en", { granularity: "grapheme" }) : null;
export function splitEmoji(s: string): string[] {
  if (seg) return [...seg.segment(s)].map((x) => x.segment);
  return [...s];
}

const RECENT_KEY = "veil:recent-emoji";
export function recentEmoji(): string[] {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]");
  } catch {
    return [];
  }
}
export function pushRecentEmoji(e: string) {
  const r = [e, ...recentEmoji().filter((x) => x !== e)].slice(0, 32);
  localStorage.setItem(RECENT_KEY, JSON.stringify(r));
}
